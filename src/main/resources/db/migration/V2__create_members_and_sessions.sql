-- HJ-003: 회원과 서버 세션.
-- 회원은 로그인 ID·비밀번호 해시·역할·생성 시각만 저장한다(추가 개인정보 없음). 초기 데이터로 계정을 만들지 않는다.
CREATE TABLE members (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    login_id      VARCHAR(30)  CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    DATETIME(6)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_members_login_id UNIQUE (login_id),
    CONSTRAINT ck_members_login_id_format CHECK (login_id REGEXP '^[a-z0-9_]{4,30}$'),
    CONSTRAINT ck_members_password_hash_argon2id CHECK (password_hash LIKE '$argon2id$%'),
    CONSTRAINT ck_members_role CHECK (role IN ('MEMBER', 'OPERATOR'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

-- Spring Session JDBC 표준 MySQL 스키마. 세션 속성 FK의 ON DELETE CASCADE는 Spring Session의 세션 삭제가
-- 전제로 하는 동작이라 유지한다(도메인 테이블의 cascade 금지 규칙과 별개). PRINCIPAL_NAME에는 회원 ID만 기록한다.
CREATE TABLE SPRING_SESSION (
    PRIMARY_ID            CHAR(36)     NOT NULL,
    SESSION_ID            CHAR(36)     NOT NULL,
    CREATION_TIME         BIGINT       NOT NULL,
    LAST_ACCESS_TIME      BIGINT       NOT NULL,
    MAX_INACTIVE_INTERVAL INT          NOT NULL,
    EXPIRY_TIME           BIGINT       NOT NULL,
    PRINCIPAL_NAME        VARCHAR(100),
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
) ENGINE = InnoDB ROW_FORMAT = DYNAMIC;

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36)     NOT NULL,
    ATTRIBUTE_NAME     VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES    BLOB         NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES SPRING_SESSION (PRIMARY_ID) ON DELETE CASCADE
) ENGINE = InnoDB ROW_FORMAT = DYNAMIC;
