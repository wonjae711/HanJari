"""Project identity and the explicitly supported execution adapter.

Profiles are local configuration, never instructions generated by an LLM.
Automation documentation stays in HanJari; product records use project pages.
"""
import copy
import re
import subprocess
import uuid
from pathlib import Path
import controller as c
import project_planning as p
from verification_evidence import EXPECTED

EMPTY_BASELINE = {'surefire-reports': {}, 'failsafe-reports': {}}
STACK = 'spring-maven-mysql'

def git(repo, *args):
    return subprocess.check_output(['git', '-C', str(repo), *args], text=True,
                                   stderr=subprocess.PIPE).strip()

def remote_name(value):
    match = re.fullmatch(r'(?:https://github\.com/|git@github\.com:)([\w.-]+/[\w.-]+?)(?:\.git)?/?', value)
    if not match: raise ValueError('Use a GitHub origin URL without credentials')
    return match[1].lower()

def repository(repo):
    repo = Path(repo).resolve()
    root = Path(git(repo, 'rev-parse', '--show-toplevel')).resolve()
    if root != repo: raise ValueError('Select the repository root, not a subdirectory')
    return repo, remote_name(git(repo, 'remote', 'get-url', 'origin'))

def validate(profile):
    if not re.fullmatch(r'[a-z][a-z0-9-]{1,39}', profile['id']): raise ValueError('Invalid project ID')
    if not re.fullmatch(r'[A-Z][A-Z0-9]{1,11}', profile['prefix']): raise ValueError('Invalid task prefix')
    if profile['stack'] != STACK: raise ValueError('Only spring-maven-mysql is supported')
    if not profile['title'].strip() or not profile['idea'].strip(): raise ValueError('Title and idea required')
    if len(profile['idea']) > 80000: raise ValueError('Idea too large')
    for name in ('record_page', 'source_page'):
        if profile.get(name): profile[name] = str(uuid.UUID(profile[name]))
    if not profile.get('record_page'): raise ValueError('Project record page required')
    if profile.get('source_page') == profile['record_page']:
        raise ValueError('Source and output pages must differ to prevent self-triggered revisions')
    baseline = profile['baseline']
    if set(baseline) != set(EMPTY_BASELINE): raise ValueError('Invalid baseline folders')
    for suites in baseline.values():
        if not isinstance(suites, dict): raise ValueError('Invalid baseline')
        for name, count in suites.items():
            if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*(?:Test|IT)', name) or type(count) is not int or count < 1:
                raise ValueError('Invalid baseline suite')
    names = profile['test_db_env']
    if len(names) != 3 or {n.rsplit('_', 1)[-1] for n in names} != {'URL', 'USERNAME', 'PASSWORD'} or any(not re.fullmatch(r'[A-Z][A-Z0-9_]*_TEST_DB_(?:URL|USERNAME|PASSWORD)', n) for n in names):
        raise ValueError('Three explicit test DB environment names required')
    if type(profile['first_feature']) is not int or not 1 <= profile['first_feature'] <= 99999:
        raise ValueError('Invalid first feature number')
    return profile

def context(profile):
    validate(profile)
    return {k: copy.deepcopy(profile[k]) for k in (
        'id', 'title', 'project_dir', 'remote', 'prefix', 'stack', 'baseline',
        'first_feature', 'test_db_env', 'source_page', 'record_page')}

def configuration(profile, shared):
    config = copy.deepcopy(shared)
    config['project_dir'] = profile['project_dir']
    config['base_branch'] = profile.get('base_branch', 'main')
    config['project_context'] = context(profile)
    config['test_db_env'] = profile['test_db_env']
    home = c.read(c.ROOT / 'integrations.json')
    settings = copy.deepcopy(home)
    settings['project_title'] = profile['title']
    settings['project_id'] = profile['id']
    settings['github'] = {'repository': profile['remote'], 'base_branch': config['base_branch'], 'draft': True}
    settings['notion'] = {'sync_mode': 'direct-api', 'tasks': {},
                         'knowledge_pages': {'plans': profile['record_page'], 'activity': profile['record_page']}}
    if profile['id'] == 'hanjari': settings['notion'] = copy.deepcopy(home['notion'])
    config['integrations'] = settings
    config['automation_pages'] = home.get('notion', {}).get('knowledge_pages', {})
    config['delivery_root'] = str(Path(profile['state_dir']) / 'delivery')
    return config

def check_binding(state, config):
    expected = state['task'].get('project_context')
    configured = config.get('project_context')
    if expected is None and configured is None: return  # Legacy pilot/planning.
    if expected != configured or not expected:
        raise ValueError('Project identity differs from the saved task; use workspace.py')
    if Path(expected['project_dir']).resolve() != Path(config['project_dir']).resolve():
        raise ValueError('Wrong project working directory')
    if state['mode'] == 'live':
        _, remote = repository(config['project_dir'])
        if remote != expected['remote']: raise ValueError('Git origin changed; user review required')

